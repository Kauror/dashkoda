"""Give GA4 a reporting-day history instead of a single current reading.

`WebsiteTrafficObservation` carried `is_current` unique per **source**: one
current row in the entire table. That is a "latest reading" model, and it cannot
hold a five-year daily history at all — publishing yesterday retired the day
before it. It is replaced by `Ga4DailySnapshot`, whose current row is unique per
**reporting date**, plus the page and channel rows a day is made of.

## The existing rows are carried over, not dropped

Whatever the deployment has already collected becomes revision 1 of its own
reporting day, keeping its figures, its source, its artifact and its import run,
so the audit trail still leads from the published number back to the run that
produced it. `period_end` becomes `report_date`; the observations this collector
publishes have always been single days, so no period is being flattened.

Their checksum is computed here in exactly the canonical form the collector now
uses. A migrated day therefore reads as *unchanged* only if the next collection
finds the same figures — and it will not, because the new collector also asks
for new users, engaged sessions and engagement duration. The first run after
this migration republishes those days as revision 2, with the migrated row kept
as the superseded revision. That is the honest outcome: the day genuinely has
more measured about it than it did before.

Safe on an empty database and on a populated one. It reads what is there and
writes one row per existing observation; there is no assumption about how many
rows that is, including none.
"""

