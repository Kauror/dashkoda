def _migrated_checksum(observation) -> str:
    """The canonical digest of this observation, in the collector's own form.

    Written out here rather than imported from `apps.visibility.ga4`: a
    migration must keep producing the same bytes years from now, and importing
    live code would let a later refactor silently change what a historical row
    claims its checksum was.
    """
    payload = {
        "schema": "2.0",
        "source": "ga4",
        "report_date": observation.period_end.isoformat(),
        "site": {
            "sessions": observation.sessions,
            "active_users": observation.active_users,
            "new_users": None,
            "page_views": observation.page_views,
            "engaged_sessions": None,
            "user_engagement_seconds": None,
        },
        "has_page_detail": False,
        "has_channel_detail": False,
        "pages": [],
        "channels": [],
    }
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


